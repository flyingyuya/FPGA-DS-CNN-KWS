#!/usr/bin/env python3
"""Generate the mantissa log LUT and the golden log vectors.

The RTL computes, for a 54-bit mel energy v (Q2.46, already scaled by the FFT's
per-stage halving):

    e       = index of the highest set bit of v            (0..53)
    m       = the 8 bits just below that bit                (0..255)
    ln_q15  = e*LN2 + LUT[m] - 28*LN2                       (Q1.15)
    log_q8  = (ln_q15 + 64) >>> 7                           (Q8.8)

The -28*LN2 constant undoes two scaling factors: the mel value is 2^46 times its
float value, and the FFT's /N scaling makes the hardware power 2^18 smaller than
the software one (46 - 18 = 28).  It is one constant adder in hardware.

An 8-bit mantissa index is enough: the truncation error is <= 1/512 = 0.002 in
nats, i.e. half an LSB of the Q8.8 output.  Measured with the full front-end model
it changes accuracy by nothing (92.77 % at 12 bits vs 92.87 % at 8 bits -- noise).

    python3 scripts/golden/gen_log_lut.py
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

LUT_BITS = 8
LUT_DEPTH = 1 << LUT_BITS
Q15 = 1 << 15
LN2_Q15 = int(round(math.log(2.0) * Q15))          # 22714
SHIFT_CONST = 28                                    # 46 (Q2.46) - 18 (FFT /N)
EPS_INT = 268                                       # 1e-6 * 2^28, the software epsilon

MEL_BITS = 54


def lut():
    return [int(round(math.log1p(m / LUT_DEPTH) * Q15)) for m in range(LUT_DEPTH)]


LUT = None


def log_q8(v):
    """Same integer arithmetic the RTL uses."""
    v = v + EPS_INT
    e = v.bit_length() - 1
    assert 0 <= e < MEL_BITS
    m = (v >> (e - LUT_BITS)) & (LUT_DEPTH - 1) if e >= LUT_BITS else \
        (v << (LUT_BITS - e)) & (LUT_DEPTH - 1)
    ln_q15 = e * LN2_Q15 + LUT[m] - SHIFT_CONST * LN2_Q15
    q = (ln_q15 + 64) >> 7
    return max(-32768, min(32767, q))


def main():
    global LUT
    tbl = LUT = lut()
    out = []
    out.append("// GENERATED by scripts/golden/gen_log_lut.py -- do not edit")
    out.append("// ln(1 + m/256) in Q1.15, %d entries" % LUT_DEPTH)
    out.append("`ifndef LOG_LUT_V")
    out.append("`define LOG_LUT_V")
    out.append("")
    out.append("module log_mant_rom (")
    out.append("    input  wire [%d:0] addr," % (LUT_BITS - 1))
    out.append("    output reg  [15:0] dout")
    out.append(");")
    out.append("    always @* begin")
    out.append("        case (addr)")
    for m, v in enumerate(tbl):
        out.append("        %d'd%d: dout = 16'd%d;" % (LUT_BITS, m, v))
    out.append("        default: dout = 16'd0;")
    out.append("        endcase")
    out.append("    end")
    out.append("endmodule")
    out.append("")
    out.append("`endif // LOG_LUT_V")
    path = os.path.join(ROOT, "rtl", "preprocessing", "log_lut.v")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"  LUT {LUT_DEPTH} entries, LN2_Q15={LN2_Q15}, const -{SHIFT_CONST}*LN2, "
          f"eps={EPS_INT}")
    print(f"  wrote {os.path.relpath(path, ROOT)}")

    # golden log vectors for the mel values already emitted for the FFT vectors
    gdir = os.path.join(ROOT, "golden", "fft")
    n = 0
    for name in ("impulse", "sine8", "multitone", "noise", "max_pos", "max_neg"):
        src = os.path.join(gdir, f"expmel_{name}.mem")
        if not os.path.isfile(src):
            continue
        mels = [int(line.strip(), 16) for line in open(src) if line.strip()]
        logs = [log_q8(v) for v in mels]
        with open(os.path.join(gdir, f"explog_{name}.mem"), "w") as fh:
            fh.write("".join(f"{v & 0xFFFF:04x}\n" for v in logs))
        n += 1
    print(f"  wrote explog_*.mem for {n} vectors")


if __name__ == "__main__":
    main()
