#!/usr/bin/env python3
"""Generate the mel-filterbank ROMs for rtl/preprocessing/mel_fb.v.

The accelerator's mel banks are triangular, always non-negative, and the peak of
every filter is exactly 1.0.  Storing them as *unsigned* Q1.15 (1.0 = 32768) keeps
the peak exact -- signed Q1.15 would clip it to 32767 and bias every filter's
output slightly low.

Two ROMs:
  mel_span_rom[f] = {base[9:0], len[6:0], lo[8:0]}   f = 0..39
  mel_coef_rom[i] = Q1.15 coefficient                i = 0..NCOEF-1

The 468 coefficients are packed contiguously (each filter's contiguous bin span),
so the engine walks one filter at a time with a single multiplier.

    python3 scripts/golden/gen_mel_rom.py
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "software"))
from features import mel_filterbank                                  # noqa: E402

NBIN = 256          # the FFT delivers bins 0..255 (bin 256 never has weight)


def build():
    fb = mel_filterbank()[:, :NBIN]
    spans, coefs = [], []
    for f in range(fb.shape[0]):
        idx = np.nonzero(fb[f])[0]
        if len(idx) == 0:
            spans.append((0, 0, 0))
            continue
        lo, hi = int(idx[0]), int(idx[-1]) + 1
        c = np.round(fb[f, lo:hi] * (1 << 15)).astype(np.int64)
        assert c.max() <= (1 << 15), "peak must be exactly 1.0 in Q1.15"
        spans.append((len(coefs), hi - lo, lo))
        coefs.extend(int(v) for v in c)
    return spans, coefs


def main():
    spans, coefs = build()
    ncoef = len(coefs)
    depth = 1
    while depth < ncoef:
        depth *= 2
    aw = max(1, int(depth - 1).bit_length())
    fw = max(1, int(len(spans) - 1).bit_length())

    out = []
    out.append("// GENERATED by scripts/golden/gen_mel_rom.py -- do not edit")
    out.append("// mel filterbank: %d filters, %d non-zero Q1.15 coefficients "
               "(1.0 = 32768, unsigned)" % (len(spans), ncoef))
    out.append("`ifndef MEL_ROM_V")
    out.append("`define MEL_ROM_V")
    out.append("")
    out.append("module mel_coef_rom (")
    out.append("    input  wire [%d:0] addr," % (aw - 1))
    out.append("    output reg  [15:0] dout")
    out.append(");")
    out.append("    always @* begin")
    out.append("        case (addr)")
    for i, v in enumerate(coefs):
        out.append("        %d'd%d: dout = 16'd%d;" % (aw, i, v))
    out.append("        default: dout = 16'd0;")
    out.append("        endcase")
    out.append("    end")
    out.append("endmodule")
    out.append("")
    out.append("module mel_span_rom (")
    out.append("    input  wire [%d:0] addr," % (fw - 1))
    out.append("    output reg  [24:0] dout        // {base[9:0], len[6:0], lo[7:0]}")
    out.append(");")
    out.append("    always @* begin")
    out.append("        case (addr)")
    for i, (base, ln, lo) in enumerate(spans):
        out.append("        %d'd%d: dout = {10'd%d, 7'd%d, 8'd%d};" % (fw, i, base, ln, lo))
    out.append("        default: dout = 25'd0;")
    out.append("        endcase")
    out.append("    end")
    out.append("endmodule")
    out.append("")
    out.append("`endif // MEL_ROM_V")

    path = os.path.join(ROOT, "rtl", "preprocessing", "mel_rom.v")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"  filters {len(spans)}, coefficients {ncoef}, rom depth {depth}, "
          f"addr {aw} bit, filter addr {fw} bit")
    print(f"  wrote {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
